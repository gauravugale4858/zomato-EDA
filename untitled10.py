import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import os

# Define the path to the CSV file
csv_file_path = '/content/extracted_data/Zomato Restaurant Dataset.csv'

# Check if the file exists before attempting to load
if os.path.exists(csv_file_path):
    df = pd.read_csv(csv_file_path)
    print(f"Successfully loaded '{csv_file_path}' into a DataFrame.")
    display(df.head())
else:
    print(f"Error: The file '{csv_file_path}' does not exist. Please ensure the zip file is extracted correctly.")
    df = None # Set df to None if file not found to avoid errors later

"""### Dataset Overview"""

if df is not None:
    print("\nDataFrame Info:")
    df.info()

    print("\nDescriptive Statistics:")
    display(df.describe(include='all'))

    print("\nMissing Values:")
    display(df.isnull().sum().sort_values(ascending=False))

"""### Visualizing Key Distributions"""

if df is not None:
    # Distribution of Aggregate Ratings
    fig, ax = plt.subplots(figsize=(10, 6))
    sns.histplot(df['Aggregate rating'], bins=10, kde=True, ax=ax)
    ax.set_title('Distribution of Restaurant Aggregate Ratings')
    ax.set_xlabel('Aggregate Rating')
    ax.set_ylabel('Number of Restaurants')
    plt.tight_layout()
    plt.show()

if df is not None:
    # Distribution of Cost
    cost_column = 'Average Cost for two'

    if cost_column in df.columns:
        fig, ax = plt.subplots(figsize=(10, 6))
        sns.histplot(df[cost_column], bins=20, kde=True, ax=ax)
        ax.set_title('Distribution of Average Cost for Two')
        ax.set_xlabel('Average Cost for Two')
        ax.set_ylabel('Number of Restaurants')
        plt.tight_layout()
        plt.show()
    else:
        print(f"The '{cost_column}' column was not found in the DataFrame. Skipping Cost distribution plot.")

if df is not None:
    # Count of Restaurants by City
    if 'City' in df.columns:
        fig, ax = plt.subplots(figsize=(12, 7))
        city_counts = df['City'].value_counts().head(10) # Top 10 cities
        # Addressing FutureWarning: Passing `palette` without assigning `hue` is deprecated.
        # Explicitly setting `hue=city_counts.index` and `legend=False`.
        sns.barplot(x=city_counts.index, y=city_counts.values, ax=ax, palette='viridis', hue=city_counts.index, legend=False)
        ax.set_title('Top 10 Cities by Number of Restaurants')
        ax.set_xlabel('City')
        ax.set_ylabel('Number of Restaurants')
        plt.xticks(rotation=45, ha='right')
        plt.tight_layout()
        plt.show()
    else:
        print("The 'City' column was not found in the DataFrame. Skipping City count plot.")

"""### Exploring Relationships and Categorical Data"""

if df is not None:
    # Scatter plot: Aggregate Rating vs. Average Cost for two
    cost_column = 'Average Cost for two'
    rating_column = 'Aggregate rating'

    if cost_column in df.columns and rating_column in df.columns:
        fig, ax = plt.subplots(figsize=(12, 7))
        sns.scatterplot(x=df[cost_column], y=df[rating_column], alpha=0.6, ax=ax)
        ax.set_title(f'{rating_column} vs. {cost_column}')
        ax.set_xlabel(cost_column)
        ax.set_ylabel(rating_column)
        plt.tight_layout()
        plt.show()
    else:
        print(f"Could not plot relationship: '{cost_column}' or '{rating_column}' column not found.")

if df is not None:
    # Top 10 Cuisines
    if 'Cuisines' in df.columns:
        # Cuisines can be comma-separated, so we need to split and count them individually
        all_cuisines = df['Cuisines'].dropna().str.split(', ').explode()
        top_cuisines = all_cuisines.value_counts().head(10)

        fig, ax = plt.subplots(figsize=(12, 7))
        sns.barplot(x=top_cuisines.index, y=top_cuisines.values, ax=ax, palette='crest', hue=top_cuisines.index, legend=False)
        ax.set_title('Top 10 Most Common Cuisines')
        ax.set_xlabel('Cuisine')
        ax.set_ylabel('Number of Restaurants')
        plt.xticks(rotation=45, ha='right')
        plt.tight_layout()
        plt.show()
    else:
        print("The 'Cuisines' column was not found in the DataFrame. Skipping Cuisines plot.")

if df is not None:
    # Scatter plot: Aggregate Rating vs. Average Cost for two
    cost_column = 'Average Cost for two'
    rating_column = 'Aggregate rating'

    if cost_column in df.columns and rating_column in df.columns:
        fig, ax = plt.subplots(figsize=(12, 7))
        sns.scatterplot(x=df[cost_column], y=df[rating_column], alpha=0.6, ax=ax)
        ax.set_title(f'{rating_column} vs. {cost_column}')
        ax.set_xlabel(cost_column)
        ax.set_ylabel(rating_column)
        plt.tight_layout()
        plt.show()
    else:
        print(f"Could not plot relationship: '{cost_column}' or '{rating_column}' column not found.")